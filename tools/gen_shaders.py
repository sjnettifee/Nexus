"""
gen_shaders.py -- compile src/gpu/shaders/*.comp to SPIR-V and emit shader_spirv.h.

Replaces compile_shaders.bat / compile_shaders.sh (two scripts that had to be kept
in sync by hand).  Python standard library only; same output on every OS.

Run by CMake into the BUILD directory, never into the source tree:
    gen_shaders.py --shaders-dir src/gpu/shaders --out build/gen/gpu/shader_spirv.h \
                   [--glslc PATH | --glslang PATH]

Warns about .comp files that are not in the table. Fails (non-zero exit, no output file) if
  * any shader in the table below is missing or fails to compile,
  * the output would contain a duplicate symbol,

"""
