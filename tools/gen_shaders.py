def die(msg):
    print("gen_shaders: ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def usable(p):
    return bool(p) and "NOTFOUND" not in p and os.path.isfile(p)


def compile_one(src, spv, glslc, glslang):
    if usable(glslc):
        cmd = [glslc, "-o", spv, src]
    elif usable(glslang):
        cmd = [glslang, "-V", "-S", "comp", src, "-o", spv]
    else:
        die("no shader compiler (need glslc or glslangValidator)")
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    if r.returncode != 0:
        die("failed to compile %s:\n%s" % (os.path.basename(src), r.stdout))
    with open(spv, "rb") as f:
        data = f.read()
    if len(data) < 20 or len(data) % 4 or struct.unpack("<I", data[:4])[0] != 0x07230203:
        die("%s: compiler output is not valid SPIR-V" % os.path.basename(src))
    return data


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--shaders-dir", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--glslc", default="")
    ap.add_argument("--glslang", default="")
    a = ap.parse_args()

    names = [n for n, _ in SHADERS]
    syms = [s for _, s in SHADERS]
    if len(set(names)) != len(names) or len(set(syms)) != len(syms):
        die("duplicate entry in SHADERS table")

    present = {f[:-5] for f in os.listdir(a.shaders_dir) if f.endswith(".comp")}
    missing = [n for n in names if n not in present]
    extra = sorted(present - set(names))
    if missing:
        die("shader source(s) missing from %s: %s" % (a.shaders_dir, ", ".join(missing)))
    if extra:
        print("gen_shaders: WARNING: not in the SHADERS table, ignored: %s\n"
              "  (add to tools/gen_shaders.py if the backend should use them)" % ", ".join(extra),
              file=sys.stderr)

    out = ["// Auto-generated by tools/gen_shaders.py -- do not edit\n",
           "#pragma once\n#include <cstdint>\n#include <cstddef>\n"]
    with tempfile.TemporaryDirectory() as td:
        for n, sym in SHADERS:
            data = compile_one(os.path.join(a.shaders_dir, n + ".comp"),
                               os.path.join(td, n + ".spv"), a.glslc, a.glslang)
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            out.append("static const uint32_t %s[]={%s};\n" % (sym, ",".join(hex(w) for w in words)))
            out.append("static const size_t %sSize=sizeof(%s);\n" % (sym, sym))

    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    tmp = a.out + ".tmp"
    with open(tmp, "w", newline="\n") as f:
        f.write("".join(out))
    os.replace(tmp, a.out)
    print("gen_shaders: wrote %s (%d shaders)" % (a.out, len(SHADERS)))


if __name__ == "__main__":
    main()
