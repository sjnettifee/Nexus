#!/usr/bin/env bash
# smoke_test.sh -- prove a release folder works on THIS computer.
#   scripts/smoke_test.sh [SERVER_FOLDER] [MODEL_FILE]
#   SERVER_FOLDER = folder holding nexus_server (default: ./nexus-usb/server, else ./dist)
#   MODEL_FILE    = optional; with it the test also loads the model, asks one question and checks that words come back.
# Needs: curl.  Uses a throw-away data folder and a random port; changes nothing else.  Exit code 0 = everything passed.
set -u
SRV_DIR="${1:-}"; MODEL="${2:-}"
if [ -z "$SRV_DIR" ]; then for d in ./nexus-usb/server ./server ./dist .; do [ -f "$d/nexus_server" ] || [ -f "$d/nexus_server.exe" ] && { SRV_DIR="$d"; break; }; done; fi
[ -n "$SRV_DIR" ] || { echo "FAIL: no nexus_server found (pass its folder as the first argument)"; exit 2; }
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) EXE=".exe" ;; *) EXE="" ;; esac
SRV="$SRV_DIR/nexus_server$EXE"
PASS=0; FAIL=0
ok()  { echo "  PASS  $*"; PASS=$((PASS+1)); }
bad() { echo "  FAIL  $*"; FAIL=$((FAIL+1)); }
[ -f "$SRV" ] || { echo "FAIL: $SRV missing"; exit 2; }

echo "[1] dispatcher and engine files in $SRV_DIR"
T="$("$SRV" --which-tier 2>&1)"; rc=$?
if [ $rc -eq 0 ] && [ -n "$T" ]; then ok "dispatcher picked: $T"; else bad "dispatcher could not pick an engine build ($T)"; fi
n=0; for f in "$SRV_DIR"/nexus_server_v[234]"$EXE"; do [ -f "$f" ] && n=$((n+1)); done
[ $n -gt 0 ] && ok "$n engine build(s) present" || bad "no nexus_server_v2/v3/v4 next to the dispatcher"
for t in v2 v3 v4; do
  if [ -f "$SRV_DIR/nexus_server_$t$EXE" ]; then
    ls "$SRV_DIR"/libnexus_$t.* >/dev/null 2>&1 && ok "library for $t present" || bad "nexus_server_$t has no libnexus_$t next to it"
  fi
done

echo "[2] hardware probe"
P="$("$SRV" --probe 2>/dev/null)"
case "$P" in *'"cpu"'*) ok "probe answered: $(echo "$P" | head -c 160 | tr '\n' ' ')..." ;; *) bad "probe gave no CPU info: $(echo "$P" | head -c 200)" ;; esac

if [ -z "$MODEL" ]; then echo; echo "(no model given: skipping the load / chat / restart checks)"; echo "RESULT: $PASS passed, $FAIL failed"; [ $FAIL -eq 0 ]; exit; fi
command -v curl >/dev/null || { bad "curl is needed for the model test"; echo "RESULT: $PASS passed, $FAIL failed"; exit 1; }
[ -f "$MODEL" ] || { echo "FAIL: model not found: $MODEL"; exit 2; }

WORK="$(mktemp -d)"; PORT=$((20000 + RANDOM % 20000)); LOG="$WORK/server.log"; PID=""
cleanup() { [ -n "$PID" ] && kill "$PID" 2>/dev/null; sleep 1; [ -n "$PID" ] && kill -9 "$PID" 2>/dev/null; rm -rf "$WORK"; }
trap cleanup EXIT
start() { ( cd "$WORK" && exec "$SRV" --model "$MODEL" --port "$PORT" --host 127.0.0.1 ) >"$LOG" 2>&1 & PID=$!; }
wait_up() {   # wait_up <seconds>
  local i=0; while [ $i -lt "$1" ]; do
    kill -0 "$PID" 2>/dev/null || return 2
    curl -s -m 2 "http://127.0.0.1:$PORT/api/boot" 2>/dev/null | grep -q . && return 0
    sleep 2; i=$((i+2)); done; return 1; }

echo "[3] load the model and answer one question (port $PORT, first start can take a few minutes)"
start; wait_up "${LOAD_TIMEOUT:-900}"; r=$?
if [ $r -ne 0 ]; then bad "server did not come up (exit/timeout code $r). Last log lines:"; tail -n 15 "$LOG" | sed 's/^/        /'; echo "RESULT: $PASS passed, $FAIL failed"; exit 1; fi
ok "server answered after loading"
BOOT1="$(curl -s -m 5 "http://127.0.0.1:$PORT/api/boot")"
OUTF="$WORK/chat.out"
curl -s -N -m "${CHAT_TIMEOUT:-300}" -H 'Content-Type: application/json' -X POST "http://127.0.0.1:$PORT/api/chat" \
  -d '{"messages":[{"role":"user","content":"Reply with one short sentence: what colour is the sky on a clear day?"}],"temperature":0,"turn_id":"smoke1"}' >"$OUTF" 2>/dev/null
events=$(grep -c '^data:' "$OUTF" 2>/dev/null || true)
if [ "${events:-0}" -ge 3 ] && ! grep -qi '"error"' "$OUTF"; then ok "reply streamed ($events events): $(grep '^data:' "$OUTF" | head -c 300 | tr '\n' ' ')"
else bad "no usable reply (events=$events). First bytes: $(head -c 300 "$OUTF")"; fi
kill -0 "$PID" 2>/dev/null && ok "server still alive after the reply" || bad "server died while answering"
grep -qiE 'segmentation|SIGSEGV|crash|bad_alloc' "$LOG" && bad "crash words in the server log" || ok "no crash words in the log"

echo "[4] restart safety"
kill "$PID" 2>/dev/null; sleep 2; kill -9 "$PID" 2>/dev/null; PID=""
start; wait_up "${LOAD_TIMEOUT:-900}"; r=$?
if [ $r -eq 0 ]; then
  BOOT2="$(curl -s -m 5 "http://127.0.0.1:$PORT/api/boot")"
  [ "$BOOT1" != "$BOOT2" ] && ok "restart gives a new boot id (old browser pages will notice)" || bad "boot id did not change after a restart"
  # nothing may be generated by itself after a restart: the log must hold no chat request that we did not send
  sleep 3; grep -q '\[chat\] POST' "$LOG" && bad "server started generating after restart without being asked" || ok "idle after restart (no request replayed)"
else bad "second start failed"; tail -n 10 "$LOG" | sed 's/^/        /'; fi
echo; echo "RESULT: $PASS passed, $FAIL failed"; [ $FAIL -eq 0 ]
