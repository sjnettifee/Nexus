/*
 * nexus/src/gguf/quant.h + quant.cpp
 *
 * Dequantization: convert compressed weight formats → float32 for compute.
 *
 * Formats implemented (in order of real-world usage):
 *   Q8_0   — 8-bit, simplest, easiest to verify first
 *   Q4_0   — 4-bit basic, common in smaller models
 *   Q4_K   — 4-bit K-quant (superblocks), what most quality GGUFs use
 *   Q5_K   — 5-bit K-quant, slightly better quality
 *   Q6_K   — 6-bit K-quant, near-lossless
 *   F16    — already float, just cast
 *   F32    — passthrough
 *
 * K-quant design (Georgi Gerganov's invention, credit where due):
 *   Instead of one scale per 32 elements, use a "superblock" of 256 elements
 *   with a global scale + 8 sub-scales (one per 32 elements).
 *   The sub-scales are themselves quantized to 6 bits.
 *   This gives much better quality at the same bit rate.
 *
 * We output float32. Caller can convert to float16 if needed.
 * All functions are designed to be called on one block at a time
 * so they compose cleanly with the matmul kernels.
 */

