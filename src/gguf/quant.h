enum class QuantType : int {
    F32  = 0,
    F16  = 1,
    Q4_0 = 2,
    Q5_0 = 6,
    Q8_0 = 8,
    Q2_K = 10,
    Q3_K = 11,
    Q4_K = 12,
    Q5_K = 13,
    Q6_K = 14,
    BF16 = 30,

    // Nexus native quants from .nxm models
    NQ4_G64 = 1004,
    NQ5_G64 = 1005,
    NQ6_G64 = 1006,
    NQ8_G64 = 1008,
};

// Dequantize `n_elements` values from `src` (quantized) into `dst` (float32)
// n_elements must be a multiple of the block size for the given type
void dequantize(const void* src, float* dst, size_t n_elements, QuantType type);

// Dequantize a row of a weight matrix (most common call pattern)
// row_idx selects which row. n_cols is the number of columns.
