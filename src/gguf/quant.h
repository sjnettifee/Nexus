inline void dequantize(const void* src, float* dst, size_t n_elements, QuantType type) {
    switch (type) {

    case QuantType::F32: {
        memcpy(dst, src, n_elements * sizeof(float));
        break;
    }

    case QuantType::F16: {
        const uint16_t* s = (const uint16_t*)src;
        for (size_t i = 0; i < n_elements; ++i) {
            dst[i] = f16_to_f32(s[i]);
        }
        break;
    }

    case QuantType::BF16: {
        const uint16_t* s = (const uint16_t*)src;
        for (size_t i = 0; i < n_elements; ++i) {
            dst[i] = bf16_to_f32(s[i]);
        }
        break;
    }

    case QuantType::Q8_0: {
        const BlockQ8_0* blocks = (const BlockQ8_0*)src;
        const size_t full = n_elements / 32;
        const size_t rem  = n_elements % 32;

        for (size_t b = 0; b < full; ++b) {
            dequant_q8_0(blocks + b, dst + b * 32);
        }

        if (rem) {
            float tmp[32];
            dequant_q8_0(blocks + full, tmp);
            memcpy(dst + full * 32, tmp, rem * sizeof(float));
        }

        break;
    }

    case QuantType::Q4_0: {
        const BlockQ4_0* blocks = (const BlockQ4_0*)src;
        const size_t full = n_elements / 32;
        const size_t rem  = n_elements % 32;

        for (size_t b = 0; b < full; ++b) {
            dequant_q4_0(blocks + b, dst + b * 32);
        }

        if (rem) {
            float tmp[32];
            dequant_q4_0(blocks + full, tmp);
            memcpy(dst + full * 32, tmp, rem * sizeof(float));
        }

        break;
    }

    case QuantType::Q5_0: {
        const BlockQ5_0* blocks = (const BlockQ5_0*)src;
        const size_t full = n_elements / 32;
        const size_t rem  = n_elements % 32;

        for (size_t b = 0; b < full; ++b) {
            dequant_q5_0(blocks + b, dst + b * 32);
        }

        if (rem) {
            float tmp[32];
            dequant_q5_0(blocks + full, tmp);
            memcpy(dst + full * 32, tmp, rem * sizeof(float));
        }

        break;
    }

    case QuantType::Q4_K: {
        const BlockQ4_K* blocks = (const BlockQ4_K*)src;
        const size_t full = n_elements / 256;
        const size_t rem  = n_elements % 256;

        for (size_t b = 0; b < full; ++b) {
            dequant_q4_k(blocks + b, dst + b * 256);
        }

        if (rem) {
            float tmp[256];
            dequant_q4_k(blocks + full, tmp);
            memcpy(dst + full * 256, tmp, rem * sizeof(float));
        }
        break;
    }

    case QuantType::Q5_K: {
        const BlockQ5_K* blocks = (const BlockQ5_K*)src;
        const size_t full = n_elements / 256;
        const size_t rem  = n_elements % 256;

        for (size_t b = 0; b < full; ++b) {
            dequant_q5_k(blocks + b, dst + b * 256);
        }

        if (rem) {
            float tmp[256];
            dequant_q5_k(blocks + full, tmp);
            memcpy(dst + full * 256, tmp, rem * sizeof(float));
        }
        break;
    }

    case QuantType::Q6_K: {
        const BlockQ6_K* blocks = (const BlockQ6_K*)src;
        const size_t full = n_elements / 256;
        const size_t rem  = n_elements % 256;

        for (size_t b = 0; b < full; ++b) {
            dequant_q6_k(blocks + b, dst + b * 256);
        }

        if (rem) {
            float tmp[256];
            dequant_q6_k(blocks + full, tmp);
            memcpy(dst + full * 256, tmp, rem * sizeof(float));
        }
        break;
    }

    case QuantType::Q2_K: {
        const BlockQ2_K* blocks = (const BlockQ2_K*)src;
        const size_t full = n_elements / 256;
        const size_t rem  = n_elements % 256;

        for (size_t b = 0; b < full; ++b) {
            dequant_q2_k(blocks + b, dst + b * 256);
        }

        if (rem) {
            float tmp[256];
            dequant_q2_k(blocks + full, tmp);
            memcpy(dst + full * 256, tmp, rem * sizeof(float));
        }
        break;
    }
    case QuantType::Q3_K: {
        const BlockQ3_K* blocks = (const BlockQ3_K*)src;
        const size_t full = n_elements / 256;
        const size_t rem  = n_elements % 256;

        for (size_t b = 0; b < full; ++b) {
            dequant_q3_k(blocks + b, dst + b * 256);
        }

        if (rem) {
            float tmp[256];
            dequant_q3_k(blocks + full, tmp);
            memcpy(dst + full * 256, tmp, rem * sizeof(float));
        }
        break;
    }


    case QuantType::NQ4_G64: {
        const BlockNQ_G64<4>* blocks = (const BlockNQ_G64<4>*)src;
        const size_t full = n_elements / 64;
        const size_t rem  = n_elements % 64;
        for (size_t b = 0; b < full; ++b) dequant_nq_g64<4>(blocks + b, dst + b * 64);
        if (rem) { float tmp[64]; dequant_nq_g64<4>(blocks + full, tmp); memcpy(dst + full * 64, tmp, rem * sizeof(float)); }
        break;
    }
    case QuantType::NQ5_G64: {
        const BlockNQ_G64<5>* blocks = (const BlockNQ_G64<5>*)src;
        const size_t full = n_elements / 64;
        const size_t rem  = n_elements % 64;
        for (size_t b = 0; b < full; ++b) dequant_nq_g64<5>(blocks + b, dst + b * 64);
        if (rem) { float tmp[64]; dequant_nq_g64<5>(blocks + full, tmp); memcpy(dst + full * 64, tmp, rem * sizeof(float)); }
        break;
    }
    case QuantType::NQ6_G64: {
        const BlockNQ_G64<6>* blocks = (const BlockNQ_G64<6>*)src;
        const size_t full = n_elements / 64;
        const size_t rem  = n_elements % 64;
        for (size_t b = 0; b < full; ++b) dequant_nq_g64<6>(blocks + b, dst + b * 64);
        if (rem) { float tmp[64]; dequant_nq_g64<6>(blocks + full, tmp); memcpy(dst + full * 64, tmp, rem * sizeof(float)); }
        break;
    }
    case QuantType::NQ8_G64: {
        const BlockNQ_G64<8>* blocks = (const BlockNQ_G64<8>*)src;
        const size_t full = n_elements / 64;
        const size_t rem  = n_elements % 64;
        for (size_t b = 0; b < full; ++b) dequant_nq_g64<8>(blocks + b, dst + b * 64);
        if (rem) { float tmp[64]; dequant_nq_g64<8>(blocks + full, tmp); memcpy(dst + full * 64, tmp, rem * sizeof(float)); }
        break;
    }

    default:
        throw std::runtime_error("Unsupported quant type in dequantize()");
    }
}

inline void dequantize_row(const void* weights, float* dst,
                    size_t row_idx, size_t n_cols, QuantType type) {
    // Compute byte offset of the row in the quantized weight buffer
    size_t byte_offset = 0;

    switch (type) {
    case QuantType::F32:
        byte_offset = row_idx * n_cols * sizeof(float);
        break;
    case QuantType::F16:
        byte_offset = row_idx * n_cols * sizeof(uint16_t);
        break;
    case QuantType::BF16:
        byte_offset = row_idx * n_cols * sizeof(uint16_t);
        break;
    case QuantType::Q8_0: {
        size_t blocks_per_row = (n_cols + 31) / 32;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockQ8_0);
        break;
    }
    case QuantType::Q4_0: {
        size_t blocks_per_row = (n_cols + 31) / 32;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockQ4_0);
        break;
    }
    case QuantType::Q5_0: {
        size_t blocks_per_row = (n_cols + 31) / 32;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockQ5_0);
        break;
    }
    case QuantType::Q4_K: {
        size_t blocks_per_row = (n_cols + 255) / 256;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockQ4_K);
        break;
    }
    case QuantType::Q5_K: {
        size_t blocks_per_row = (n_cols + 255) / 256;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockQ5_K);
        break;
    }
    case QuantType::Q6_K: {
        size_t blocks_per_row = (n_cols + 255) / 256;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockQ6_K);
        break;
    }
    case QuantType::Q2_K: {
        size_t blocks_per_row = (n_cols + 255) / 256;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockQ2_K);
        break;
    }
    case QuantType::Q3_K: {
        size_t blocks_per_row = (n_cols + 255) / 256;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockQ3_K);
        break;
    }

    case QuantType::NQ4_G64: {
        size_t blocks_per_row = (n_cols + 63) / 64;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockNQ_G64<4>);
        break;
    }
    case QuantType::NQ5_G64: {
        size_t blocks_per_row = (n_cols + 63) / 64;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockNQ_G64<5>);
        break;
    }
    case QuantType::NQ6_G64: {
        size_t blocks_per_row = (n_cols + 63) / 64;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockNQ_G64<6>);
        break;
    }
    case QuantType::NQ8_G64: {
        size_t blocks_per_row = (n_cols + 63) / 64;
        byte_offset = row_idx * blocks_per_row * sizeof(BlockNQ_G64<8>);
        break;
    }
    default:
        throw std::runtime_error("Unsupported quant type in dequantize_row()");
    }

    const void* row_ptr = (const uint8_t*)weights + byte_offset;
    dequantize(row_ptr, dst, n_cols, type);
}

