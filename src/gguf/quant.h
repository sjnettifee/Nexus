// ─── Block structures (must match GGUF on-disk layout exactly) ────────────────

// Q8_0: 32 elements, 1 float16 scale, 32 int8 values = 34 bytes
struct BlockQ8_0 {
    uint16_t d;          // scale as float16
    int8_t   qs[32];     // quantized values
};
static_assert(sizeof(BlockQ8_0) == 34, "Q8_0 block size mismatch");

// Q4_0: 32 elements, 1 float16 scale, 16 bytes (two nibbles per byte) = 18 bytes
struct BlockQ4_0 {
    uint16_t d;          // scale as float16
    uint8_t  qs[16];     // 32 values packed as nibbles
};
static_assert(sizeof(BlockQ4_0) == 18, "Q4_0 block size mismatch");

// Q5_0: 32 elements, 1 float16 scale, 4 bytes high bits, 16 bytes low nibbles = 22 bytes
struct BlockQ5_0 {
    uint16_t d;
    uint8_t  qh[4];      // high bits (1 per element)
    uint8_t  qs[16];     // low 4 bits
};
static_assert(sizeof(BlockQ5_0) == 22, "Q5_0 block size mismatch");

// Q4_K: superblock of 256 elements = 144 bytes
struct BlockQ4_K {
    uint16_t d;          // super-block scale (float16)
    uint16_t dmin;       // super-block min  (float16)
    uint8_t  scales[12]; // 8 sub-block scales + 8 mins, packed into 6 bits each
    uint8_t  qs[128];    // 256 values packed as nibbles
};
static_assert(sizeof(BlockQ4_K) == 144, "Q4_K block size mismatch");

// Q5_K: superblock of 256 elements = 176 bytes
struct BlockQ5_K {
    uint16_t d;
    uint16_t dmin;
    uint8_t  scales[12];
    uint8_t  qh[32];     // high bits for 256 values
    uint8_t  qs[128];    // low 4 bits
};
static_assert(sizeof(BlockQ5_K) == 176, "Q5_K block size mismatch");

// Q6_K: superblock of 256 elements = 210 bytes
struct BlockQ6_K {
    uint8_t  ql[128];    // low 4 bits
    uint8_t  qh[64];     // high 2 bits
    int8_t   scales[16]; // sub-block scales (8 per superblock, in int8)
    uint16_t d;          // super-block scale (float16)
};
static_assert(sizeof(BlockQ6_K) == 210, "Q6_K block size mismatch");

// Q2_K: superblock of 256 elements = 84 bytes
struct BlockQ2_K {
    uint8_t  scales[16]; // 16 sub-block scales (low nibble) and mins (high nibble)
    uint8_t  qs[64];     // 256 values, 2 bits each
    uint16_t d;          // super-block scale (float16)
    uint16_t dmin;       // super-block min   (float16)
};
static_assert(sizeof(BlockQ2_K) == 84, "Q2_K block size mismatch");

// Q3_K: superblock of 256 elements = 110 bytes
struct BlockQ3_K {
    uint8_t  hmask[32];  // high bit of every value (1 = no offset, 0 = subtract 4)
    uint8_t  qs[64];     // low 2 bits of every value
    uint8_t  scales[12]; // 16 six-bit scales packed
    uint16_t d;          // super-block scale (float16)
};
static_assert(sizeof(BlockQ3_K) == 110, "Q3_K block size mismatch");
// Nexus native row/group quants: one F16 scale per 64 values, packed signed values.
// These are generated by nexus_native_quant_builder.py and are not GGUF formats.
template<int BITS>
struct BlockNQ_G64;
template<> struct BlockNQ_G64<4> { uint16_t d; uint8_t qs[32]; };
template<> struct BlockNQ_G64<5> { uint16_t d; uint8_t qs[40]; };
template<> struct BlockNQ_G64<6> { uint16_t d; uint8_t qs[48]; };
template<> struct BlockNQ_G64<8> { uint16_t d; uint8_t qs[64]; };
static_assert(sizeof(BlockNQ_G64<4>) == 34, "NQ4_G64 block size mismatch");
static_assert(sizeof(BlockNQ_G64<5>) == 42, "NQ5_G64 block size mismatch");
static_assert(sizeof(BlockNQ_G64<6>) == 50, "NQ6_G64 block size mismatch");
static_assert(sizeof(BlockNQ_G64<8>) == 66, "NQ8_G64 block size mismatch");


// ─── Float16 conversion ───────────────────────────────────────────────────────

// Convert IEEE 754 float16 bits → float32
// Uses F16C hardware instruction when compiled with -march=native on CPUs that
// support it (Intel Ivy Bridge+, AMD Ryzen+, your i7-9700K and Ryzen 5 4500U both do).
// The KV cache attention loop calls this ~millions of times per token — the hardware
// path is a single vcvtph2ps instruction vs ~15 arithmetic ops in software.
#if defined(__F16C__)
inline float f16_to_f32(uint16_t h) {
    return _mm_cvtss_f32(_mm_cvtph_ps(_mm_cvtsi32_si128((int)(uint32_t)h)));
}

// Batch: convert 8 f16 values to f32 using one _mm256_cvtph_ps instruction.
// Use this in hot loops instead of 8 individual f16_to_f32 calls.
inline void f16x8_to_f32x8(const uint16_t* src, float* dst) {
    __m128i v = _mm_loadu_si128(reinterpret_cast<const __m128i*>(src));
    _mm256_storeu_ps(dst, _mm256_cvtph_ps(v));
}
#else
inline float f16_to_f32(uint16_t h) {
    const uint32_t sign     = (h >> 15) & 1;
    const uint32_t exponent = (h >> 10) & 0x1F;
    const uint32_t mantissa = h & 0x3FF;
    uint32_t f;
    if (exponent == 0) {
        if (mantissa == 0) { f = sign << 31; }
        else {
            int e = -1; uint32_t m = mantissa;
            do { e++; m <<= 1; } while (!(m & 0x400));
            f = (sign << 31) | ((127 - 15 - e) << 23) | ((m & 0x3FF) << 13);
        }
    } else if (exponent == 0x1F) {
        f = (sign << 31) | (0xFF << 23) | (mantissa << 13);
    } else {
        f = (sign << 31) | ((exponent - 15 + 127) << 23) | (mantissa << 13);
    }
    float result; __builtin_memcpy(&result, &f, 4); return result;
}
inline void f16x8_to_f32x8(const uint16_t* src, float* dst) {
    for (int i = 0; i < 8; ++i) dst[i] = f16_to_f32(src[i]);
}
#endif

inline float bf16_to_f32(uint16_t h) {
    uint32_t bits = ((uint32_t)h) << 16;
    float result;
    std::memcpy(&result, &bits, sizeof(result));
    return result;
}

// ─── Dequantization functions ─────────────────────────────────────────────────
// Each takes a pointer to one block and writes `n_elements` float32 values.

// Q8_0: scale × qs[i]
inline void dequant_q8_0(const BlockQ8_0* block, float* out) {
    const float d = f16_to_f32(block->d);
    for (int i = 0; i < 32; ++i) {
        out[i] = d * block->qs[i];
    }
}

// Q4_0: scale × (nibble - 8)  — symmetric around 0
inline void dequant_q4_0(const BlockQ4_0* block, float* out) {
    const float d = f16_to_f32(block->d);
    for (int i = 0; i < 16; ++i) {
        const uint8_t byte = block->qs[i];
        out[2*i+0] = d * ((int)(byte & 0x0F) - 8);
        out[2*i+1] = d * ((int)(byte >> 4)   - 8);
    }
}

// Q5_0: 5-bit symmetric, high bit in qh
inline void dequant_q5_0(const BlockQ5_0* block, float* out) {
    const float d = f16_to_f32(block->d);
    uint32_t qh;
    __builtin_memcpy(&qh, block->qh, 4);

    for (int i = 0; i < 16; ++i) {
        const uint8_t byte = block->qs[i];
        const int hi0 = ((qh >> i)      & 1) << 4;
        const int hi1 = ((qh >> (i+16)) & 1) << 4;
        out[2*i+0] = d * ((int)(( byte       & 0x0F) | hi0) - 16);
        out[2*i+1] = d * ((int)(((byte >> 4) & 0x0F) | hi1) - 16);
    }
}

// Q4_K: k-quant superblock, 256 elements
// ggml layout (MUST match exactly):
//   4 groups of 64 elements; each group j uses q[j*32..j*32+31]:
//     output[j*64 +  0..31] = low  nibbles of q[j*32..j*32+31], scale[j*2]
//     output[j*64 + 32..63] = high nibbles of q[j*32..j*32+31], scale[j*2+1]
// NOT interleaved per byte — all low nibbles of a run first, then all high nibbles.
inline void dequant_q4_k(const BlockQ4_K* block, float* out) {
    const float d    = f16_to_f32(block->d);
    const float dmin = f16_to_f32(block->dmin);

    float scales[8], mins[8];
    {
        const uint8_t* sc = block->scales;
        for (int i = 0; i < 4; ++i) {
            scales[i]   =  sc[i]   & 0x3F;
            mins[i]     =  sc[i+4] & 0x3F;
            scales[i+4] = (sc[i+8] & 0x0F) | ((sc[i]   >> 6) << 4);
            mins[i+4]   = (sc[i+8] >> 4)   | ((sc[i+4] >> 6) << 4);
        }
    }

    const uint8_t* q = block->qs;
    for (int j = 0; j < 4; ++j) {
        const int is    = j * 2;
        const float d0  = d * scales[is];
        const float m0  = dmin * mins[is];
        const float d1  = d * scales[is + 1];
        const float m1  = dmin * mins[is + 1];
        const int base  = j * 64;
        const int qbase = j * 32;

        // 32 elements from low nibbles
        for (int l = 0; l < 32; ++l)
            out[base + l]      = d0 * (q[qbase + l] & 0x0F) - m0;
        // 32 elements from high nibbles
        for (int l = 0; l < 32; ++l)
            out[base + 32 + l] = d1 * (q[qbase + l] >> 4)   - m1;
    }
}

// Q5_K: k-quant superblock, 256 elements (5-bit)
// Same group layout as Q4_K, plus 1 high bit per element stored in qh[0..31].
// Each qh byte covers one element-index l across all 4 groups:
//   group 0 low:  qh[l] & (1<<0)   group 0 high: qh[l] & (1<<1)
//   group 1 low:  qh[l] & (1<<2)   group 1 high: qh[l] & (1<<3)
//   group 2 low:  qh[l] & (1<<4)   group 2 high: qh[l] & (1<<5)
//   group 3 low:  qh[l] & (1<<6)   group 3 high: qh[l] & (1<<7)
inline void dequant_q5_k(const BlockQ5_K* block, float* out) {
    const float d    = f16_to_f32(block->d);
    const float dmin = f16_to_f32(block->dmin);

    float scales[8], mins[8];
    {
        const uint8_t* sc = block->scales;
        for (int i = 0; i < 4; ++i) {
            scales[i]   =  sc[i]   & 0x3F;
            mins[i]     =  sc[i+4] & 0x3F;
            scales[i+4] = (sc[i+8] & 0x0F) | ((sc[i]   >> 6) << 4);
            mins[i+4]   = (sc[i+8] >> 4)   | ((sc[i+4] >> 6) << 4);
        }
    }

    const uint8_t* ql = block->qs;
    const uint8_t* qh = block->qh;

    for (int j = 0; j < 4; ++j) {
        const int is    = j * 2;
        const float d0  = d * scales[is];
        const float m0  = dmin * mins[is];
        const float d1  = d * scales[is + 1];
        const float m1  = dmin * mins[is + 1];
        const int base  = j * 64;
        const int qbase = j * 32;
        const uint8_t u1 = (uint8_t)(1 << (2 * j));      // bit for low-nibble elements
        const uint8_t u2 = (uint8_t)(1 << (2 * j + 1));  // bit for high-nibble elements

        for (int l = 0; l < 32; ++l)
            out[base + l]      = d0 * ((ql[qbase + l] & 0x0F) + ((qh[l] & u1) ? 16 : 0)) - m0;
        for (int l = 0; l < 32; ++l)
            out[base + 32 + l] = d1 * ((ql[qbase + l] >> 4)   + ((qh[l] & u2) ? 16 : 0)) - m1;
    }
}

// Q6_K: k-quant superblock, 256 elements (6-bit)
// ggml layout: two passes over 128 elements each.
// For l=0..31: q1=ql[l]+qh bits 0-1, q2=ql[l+32]+qh bits 2-3,
//              q3=ql[l] high nibble+qh bits 4-5, q4=ql[l+32] high nibble+qh bits 6-7
// Outputs land at l, l+32, l+64, l+96 (stride-32, not sequential).
// Scales: sc[l/16+0,2,4,6] — 8 scales total but accessed with stride 2.
inline void dequant_q6_k(const BlockQ6_K* block, float* out) {
    const float d = f16_to_f32(block->d);

    const uint8_t* ql = block->ql;    // 128 bytes
    const uint8_t* qh = block->qh;    //  64 bytes
    const int8_t*  sc = block->scales; // 16 bytes
    float* y = out;

    // Two halves of 128 elements each
    for (int n = 0; n < 2; ++n) {
        for (int l = 0; l < 32; ++l) {
            const int is = l / 16;  // 0 for l<16, 1 for l>=16
            const int8_t q1 = (int8_t)((ql[l +  0] & 0x0F) | (((qh[l] >> 0) & 3) << 4)) - 32;
            const int8_t q2 = (int8_t)((ql[l + 32] & 0x0F) | (((qh[l] >> 2) & 3) << 4)) - 32;
            const int8_t q3 = (int8_t)((ql[l +  0] >>    4) | (((qh[l] >> 4) & 3) << 4)) - 32;
            const int8_t q4 = (int8_t)((ql[l + 32] >>    4) | (((qh[l] >> 6) & 3) << 4)) - 32;
            y[l +  0] = d * sc[is + 0] * q1;
            y[l + 32] = d * sc[is + 2] * q2;
            y[l + 64] = d * sc[is + 4] * q3;
            y[l + 96] = d * sc[is + 6] * q4;
        }
        y  += 128;
        ql += 64;
        qh += 32;
        sc += 8;
    }
}


// Nexus native NQ*_G64: unpack 64 signed values and multiply by one f16 scale.
template<int BITS>
inline uint32_t nq_get_bits(const uint8_t* p, int idx) {
    const int bit = idx * BITS;
    const int byte = bit >> 3;
    const int shift = bit & 7;
    uint32_t v = (uint32_t)p[byte] >> shift;
    if (shift + BITS > 8) v |= (uint32_t)p[byte + 1] << (8 - shift);
    return v & ((1u << BITS) - 1u);
}

template<int BITS>
inline void dequant_nq_g64(const BlockNQ_G64<BITS>* block, float* out) {
    const float d = f16_to_f32(block->d);
    const int off = 1 << (BITS - 1);
    for (int i = 0; i < 64; ++i) {
        const int q = (int)nq_get_bits<BITS>(block->qs, i) - off;
        out[i] = d * (float)q;
    }
}

// Q2_K: 16 sub-blocks of 16 values; value = d*(scale&15)*q2 - dmin*(scale>>4).  Two halves of 128 values, 4 bit-planes each (ggml layout).
inline void dequant_q2_k(const BlockQ2_K* block, float* out) {
    const float d    = f16_to_f32(block->d);
    const float dmin = f16_to_f32(block->dmin);
    const uint8_t* q = block->qs;
    float* y = out;
    int is = 0;
    for (int n = 0; n < 256; n += 128) {
        int shift = 0;
        for (int j = 0; j < 4; ++j) {
            uint8_t sc = block->scales[is++];
            float dl = d * (sc & 0xF), ml = dmin * (sc >> 4);
            for (int l = 0; l < 16; ++l) *y++ = dl * (float)((q[l] >> shift) & 3) - ml;
            sc = block->scales[is++];
            dl = d * (sc & 0xF); ml = dmin * (sc >> 4);
            for (int l = 0; l < 16; ++l) *y++ = dl * (float)((q[l + 16] >> shift) & 3) - ml;
            shift += 2;
        }
        q += 32;
    }
}

// Q3_K: 16 sub-blocks of 16 values; value = d*(scale-32) * (q2 - (hmask bit ? 0 : 4)).
inline void dequant_q3_k(const BlockQ3_K* block, float* out) {
    const float d_all = f16_to_f32(block->d);
    // unpack the 16 six-bit scales (ggml layout: low 4 bits in bytes 0..7 (two per byte), top 2 bits in bytes 8..11)
    int8_t sc[16];
    for (int k = 0; k < 16; ++k) {
        const int lo = (k < 8) ? (block->scales[k] & 0xF) : (block->scales[k - 8] >> 4);
        const int hi = (block->scales[8 + (k & 3)] >> (2 * (k >> 2))) & 3;
        sc[k] = (int8_t)((lo | (hi << 4)) - 32);
    }
    const uint8_t* q  = block->qs;
    const uint8_t* hm = block->hmask;
    float* y = out;
    uint8_t m = 1;
    int is = 0;
    for (int n = 0; n < 256; n += 128) {
        int shift = 0;
        for (int j = 0; j < 4; ++j) {
            float dl = d_all * sc[is++];
            for (int l = 0; l < 16; ++l) *y++ = dl * (float)((int)((q[l] >> shift) & 3) - ((hm[l] & m) ? 0 : 4));
            dl = d_all * sc[is++];
            for (int l = 0; l < 16; ++l) *y++ = dl * (float)((int)((q[l + 16] >> shift) & 3) - ((hm[l + 16] & m) ? 0 : 4));
            shift += 2; m <<= 1;
        }
        q += 32;
    }
}

